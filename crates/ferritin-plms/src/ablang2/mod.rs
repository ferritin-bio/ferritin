//! AbLang2: a paired heavy/light antibody language model (ferritin-sxg).
//!
//! AbLang2 (Olsen, Moal & Deane, *Bioinformatics* 40(11) btae618, 2024) is a
//! ~45M-parameter masked language model over **paired antibody variable
//! domains**. It was trained to reduce germline bias, so its masked-residue
//! predictions are meant to be useful for suggesting non-germline mutations.
//! It is an antibody specialist: it is not a general protein model and not a
//! de novo generator.
//!
//! # Provenance
//!
//! | | |
//! |---|---|
//! | code | `oxpig/AbLang2` @ `586af3083c32b5fb2f0a1c855f2ad4f1cad15ec3`, BSD-3-Clause |
//! | weights | Zenodo record 10185169, `ablang2-weights.tar.gz`, BSD-3-Clause-Clear |
