//!
//! The weights date from November 2023; the paper from October 2024. The
//! weights license is BSD-3-Clause-*Clear*, which additionally disclaims any
//! patent grant — it is **not** the AGPL of some third-party wrappers. Weights
//! are downloaded from Zenodo at run time; none are vendored here.
//!
//! # Architecture
//!
//! An ESM-2-inspired pre-LayerNorm encoder: 12 blocks, width 480, 20 heads of
//! 24, interleaved rotary positions, SwiGLU feed-forward, biases everywhere,
//! LayerNorm eps `1e-12`, and a tied masked-LM head. [`model`] lists the five
//! details that each change the numbers.
//!
//! # Inputs and alignment
//!
//! Inputs are `(heavy, light)` pairs; either may be empty. [`tokenizer`]
//! explains the asymmetric special-token layout and why outputs carry a
//! per-row [`TokenRole`][tokenizer::TokenRole] rather than a fixed offset.
//!
//! # What is verified
//!
//! `tests/test_plm_ablang2.rs` compares token ids, hidden states, per-layer
//! intermediates, full masked-LM logits, a padded batch, and upstream's
//! `pseudo_log_likelihood`, `confidence` and `restore` against
//! `tests/fixtures/ablang2_parity.safetensors`, generated by
//! `scripts/generate_ablang2_fixtures.py` from the pinned official code and
//! weights. ANARCI-based alignment (`align=True` upstream) is not ported.

